"""Turn report/stats/*.json into LaTeX macros, so no number in the report is typed by hand.

Run after the notebooks:   python report/build_stats.py
Writes report/stats/stats.tex (\\input by template2026.tex) and
report/tables/tab1_3_packages.tex (from requirements.txt).

Naming: <Prefix><CamelCaseKey>, digits spelled out because LaTeX macro
names are letters only. Example: ch02_cleaning.json key
"usable_financial_sample" -> \\CleanUsableFinancialSample. Every macro is
listed with its source key in a comment above its definition.
"""

import calendar
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
STATS = HERE / "stats"
TABLES = HERE / "tables"
ROOT = HERE.parent

PREFIX = {
    "ch01_audit": "Audit",
    "ch02_cleaning": "Clean",
    "ch03_univariate": "Uni",
    "ch03_multivariate": "Multi",
    "ch04_features": "Feat",
    "ch05_modelling": "Model",
}
DIGITS = "Zero One Two Three Four Five Six Seven Eight Nine".split()


def macro_name(prefix: str, key: str) -> str:
    out = prefix
    for part in key.split("_"):
        if not part:
            continue
        spelled = "".join(DIGITS[int(ch)] if ch.isdigit() else ch for ch in part)
        out += spelled[0].upper() + spelled[1:]
    return out


def escape(s: str) -> str:
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"),
                 ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}")]:
        s = s.replace(a, b)
    return s


def thousands(v) -> str:
    return f"{int(round(v)):,}".replace(",", "{,}")


def is_p(key: str) -> bool:
    return "p" in key.split("_")


def fmt(key: str, v):
    """Return the LaTeX body for a value, or None to skip it."""
    if isinstance(v, bool) or isinstance(v, (list, dict)) or v is None:
        return None
    if isinstance(v, str):
        return escape(v)
    if is_p(key):
        if v == 0:
            return r"\ensuremath{<10^{-300}}"
        if v < 1e-3:
            mant, exp = f"{v:.1e}".split("e")
            return rf"\ensuremath{{{mant}\times10^{{{int(exp)}}}}}"
        return f"{v:.3f}"
    if "year" in key.split("_") or key == "split_year":
        return str(int(round(v)))
    if isinstance(v, float) and math.isnan(v):
        return "--"
    if abs(v) >= 1000:
        body = thousands(v)
    elif isinstance(v, int):
        body = str(v)
    elif v.is_integer() and abs(v) >= 10:
        body = str(int(v))
    else:
        # keep the precision the notebook rounded to (1.0 stays 1.0), but
        # tame binary-float artefacts such as 4.7410499999999995
        body = repr(v) if len(repr(v)) <= 7 else f"{v:.4g}"
    if body.startswith("-"):
        body = rf"\ensuremath{{-{body[1:]}}}"
    return body


def build_macros() -> int:
    lines = ["% AUTO-GENERATED by report/build_stats.py from report/stats/*.json -- do not edit.", ""]
    count = 0
    for stem, prefix in PREFIX.items():
        path = STATS / f"{stem}.json"
        if not path.exists():
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        lines.append(f"% ---- {stem}.json")
        for key, v in data.items():
            body = fmt(key, v)
            if body is None:
                continue
            name = macro_name(prefix, key)
            lines.append(f"% {key}")
            lines.append(rf"\newcommand{{\{name}}}{{{body}}}")
            count += 1
            # Derived forms: dollar amounts in millions, month numbers as names
            if isinstance(v, (int, float)) and not isinstance(v, bool) and abs(v) >= 1e6 and not is_p(key):
                lines.append(rf"\newcommand{{\{name}M}}{{{v / 1e6:,.1f}}}".replace(",", "{,}"))
                count += 1
            if key.endswith("_month") and isinstance(v, int) and 1 <= v <= 12:
                lines.append(rf"\newcommand{{\{name}Name}}{{{calendar.month_name[v]}}}")
                count += 1
        lines.append("")
    names = [ln.split("}")[0][len(r"\newcommand{"):] for ln in lines if ln.startswith(r"\newcommand")]
    dupes = {n for n in names if names.count(n) > 1}
    assert not dupes, f"duplicate macro names: {sorted(dupes)}"
    (STATS / "stats.tex").write_text("\n".join(lines), encoding="utf-8")
    return count


PURPOSE = {
    "pandas": "data frames, cleaning, aggregation",
    "numpy": "numerical arrays, log transforms",
    "matplotlib": "all static figures (vector PDF)",
    "seaborn": "shared theme, box plots, heatmaps",
    "scipy": "Mann-Whitney, Kruskal-Wallis, chi-square, Spearman",
    "scikit-learn": "pipelines, Ridge, gradient boosting, metrics, mutual information",
    "statsmodels": "OLS with HC3 errors, Breusch-Pagan, VIF, Q-Q plots",
    "missingno": "missingness matrix",
    "plotly": "interactive exploration only (no report figures)",
    "pyarrow": "Parquet storage of interim/processed data",
    "nbconvert": "headless top-to-bottom notebook execution",
}


def build_packages() -> int:
    rows = []
    for line in (ROOT / "requirements.txt").read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "==" not in line:
            continue
        pkg, ver = line.split("==", 1)
        rows.append(f"{escape(pkg)} & {escape(ver)} & {escape(PURPOSE.get(pkg, ''))} \\\\")
    TABLES.mkdir(parents=True, exist_ok=True)
    body = ["\\begin{tabular}{llp{9cm}}", "\\toprule", "package & version & used for \\\\", "\\midrule",
            *rows, "\\bottomrule", "\\end{tabular}"]
    (TABLES / "tab1_3_packages.tex").write_text("\n".join(body) + "\n", encoding="utf-8")
    return len(rows)


if __name__ == "__main__":
    n = build_macros()
    k = build_packages()
    print(f"{n} macros -> {STATS / 'stats.tex'}")
    print(f"{k} packages -> {TABLES / 'tab1_3_packages.tex'}")
